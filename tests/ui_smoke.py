"""Real browser smoke test. Run against an empty, isolated preview library."""
import json
import os
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

base = os.environ.get("LIBRARY_TEST_URL", "http://127.0.0.1:4318")
out = Path("test-results")
out.mkdir(exist_ok=True)
with sync_playwright() as p:
    browser = p.chromium.launch(headless=True)
    page = browser.new_page(viewport={"width": 1440, "height": 1000}, device_scale_factor=1)
    errors = []
    page.on("pageerror", lambda error: errors.append(str(error)))
    page.goto(base)
    page.wait_for_load_state("networkidle")
    # Discover the rendered surface before interacting.
    (out / "initial-dom.txt").write_text(page.locator("body").inner_text(), encoding="utf-8")
    expect(page.get_by_role("heading", name="全部资料", exact=True)).to_be_visible()
    page.get_by_role("button", name="收集资料", exact=True).click()
    dialog = page.get_by_role("dialog")
    dialog.get_by_role("tab", name="文本摘录").click()
    dialog.get_by_label("标题").fill("混合检索：从收藏到可引用的知识")
    dialog.get_by_label("正文", exact=True).fill("## 为什么要保留原文\n\n关键词检索擅长精确匹配，语义检索帮助发现表达不同但含义相近的内容。\n\n将两种检索结果合并，并保留来源段落，可以让每条结论都有据可查。")
    dialog.get_by_label("分类", exact=True).fill("技术/AI")
    dialog.get_by_label("专题").fill("个人知识库")
    dialog.get_by_label("标签").fill("检索，待读")
    dialog.get_by_role("button", name="保存资料", exact=True).click()
    expect(page.get_by_role("dialog")).to_have_count(0)
    expect(page.get_by_role("region", name="资料详情").get_by_role("heading", name="混合检索：从收藏到可引用的知识")).to_be_visible()
    page.get_by_label("搜索资料").fill("语义")
    expect(page.get_by_role("region", name="资料列表").get_by_role("heading", name="混合检索：从收藏到可引用的知识")).to_be_visible()
    page.get_by_role("button", name="摘录 p0002 为笔记").click()
    dialog = page.get_by_role("dialog")
    dialog.get_by_label("标题").fill("检索方案 · 阅读笔记")
    dialog.get_by_label("笔记内容").fill("关键词与语义检索可以互补。下一步：使用真实查询评估召回质量。")
    dialog.get_by_role("button", name="保存笔记", exact=True).click()
    expect(page.get_by_role("region", name="资料详情").get_by_role("heading", name="检索方案 · 阅读笔记")).to_be_visible()
    expect(page.get_by_role("heading", name="来源引用", exact=True)).to_be_visible()
    page.get_by_role("button", name="查看引用 1", exact=True).click()
    expect(page.locator('.kl-cited[data-segment-id="p0002"]')).to_be_visible()
    page.get_by_role("region", name="资料列表").get_by_role("heading", name="检索方案 · 阅读笔记").click()
    expect(page.get_by_role("region", name="资料详情").get_by_role("heading", name="检索方案 · 阅读笔记")).to_be_visible()
    page.get_by_role("button", name="编辑信息", exact=True).click()
    dialog = page.get_by_role("dialog")
    dialog.get_by_label("分类", exact=True).fill("研究/检索")
    dialog.get_by_label("标签").fill("已整理")
    dialog.get_by_role("button", name="保存修改", exact=True).click()
    expect(page.get_by_role("dialog")).to_have_count(0)
    page.reload()
    page.wait_for_load_state("networkidle")
    expect(page.get_by_role("region", name="资料列表").get_by_role("heading", name="检索方案 · 阅读笔记")).to_be_visible()
    # Import a subtitle through the real upload route, then verify timestamp rendering.
    page.get_by_role("button", name="收集资料", exact=True).click()
    dialog = page.get_by_role("dialog")
    dialog.get_by_role("tab", name="本地文件").click()
    dialog.get_by_label("选择本地文件").set_input_files({
        "name": "知识整理课程.vtt", "mimeType": "text/vtt",
        "buffer": "WEBVTT\n\n00:00:12.000 --> 00:00:18.000\n收集之后，应当记录原始出处。\n\n00:01:05.000 --> 00:01:12.000\n把资料关联到一个具体问题，知识才更容易复用。\n".encode("utf-8")
    })
    dialog.get_by_label("分类", exact=True).fill("学习/课程")
    dialog.get_by_role("button", name="保存资料", exact=True).click()
    expect(page.get_by_role("region", name="资料详情").get_by_text("00:01:05", exact=True)).to_be_visible()
    # Filtering back to all types must not send the string 'undefined'.
    page.get_by_label("按类型筛选").select_option("note")
    expect(page.get_by_role("region", name="资料列表").get_by_role("heading", name="检索方案 · 阅读笔记")).to_be_visible()
    page.get_by_label("按类型筛选").select_option("")
    expect(page.get_by_role("region", name="资料列表").get_by_role("heading", name="知识整理课程")).to_be_visible()
    page.get_by_role("region", name="资料列表").get_by_role("heading", name="混合检索：从收藏到可引用的知识").click()
    expect(page.get_by_role("region", name="资料详情").get_by_text("p0002", exact=True)).to_be_visible()
    page.screenshot(path=str(out / "library-desktop.png"), full_page=True)
    # Plain text rendering must not interpret imported HTML as executable markup.
    page.get_by_role("button", name="收集资料", exact=True).click()
    dialog = page.get_by_role("dialog")
    dialog.get_by_role("tab", name="文本摘录").click()
    dialog.get_by_label("标题").fill("文本安全验证")
    dialog.get_by_label("正文", exact=True).fill('<img src=x onerror="window.__unsafe=true"> 原文中的 HTML 仅作为文本。')
    dialog.get_by_role("button", name="保存资料", exact=True).click()
    expect(page.get_by_role("dialog")).to_have_count(0)
    assert page.evaluate("window.__unsafe === undefined")
    page.set_viewport_size({"width": 390, "height": 844})
    page.screenshot(path=str(out / "library-mobile.png"), full_page=True)
    assert page.evaluate("document.documentElement.scrollWidth <= window.innerWidth")
    assert not errors, errors
    (out / "ui-result.json").write_text(json.dumps({"passed": True, "browser": browser.version, "errors": errors, "flows": ["text capture", "Chinese search", "cited note", "metadata move", "reload persistence", "subtitle upload", "type filter reset", "XSS text rendering", "mobile overflow"]}, ensure_ascii=False, indent=2), encoding="utf-8")
    browser.close()
    print("PASS: 9 browser flows; desktop and mobile screenshots saved.")
